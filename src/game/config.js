export function readProfile() {
  try {
    const p = JSON.parse(localStorage.getItem("strikezone-profile") || "{}");
    return {
      ...DEFAULT_PROFILE,
      ...p,
      weapon: WEAPONS[p.weapon] ? p.weapon : "ak",
      skin: SKINS.some((s) => s.id === p.skin) ? p.skin : "standard",
      owned: Array.isArray(p.owned) ? p.owned : ["standard"],
      history: Array.isArray(p.history) ? p.history : [],
    };
  } catch {
    return { ...DEFAULT_PROFILE };
  }
}
